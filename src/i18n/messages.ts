const dictionaries: Record<'en' | 'zh-CN', Record<string, string>> = { en: {}, 'zh-CN': {} };
for (const [source, english, chinese] of triples) {
  dictionaries.en[source] = english;
  dictionaries['zh-CN'][source] = chinese;
}

const monthMaps: Record<'en' | 'zh-CN', Record<string, string>> = {
  en: {
    Januari: 'January', Februari: 'February', Maret: 'March', April: 'April',
    Mei: 'May', Juni: 'June', Juli: 'July', Agustus: 'August',
    September: 'September', Oktober: 'October', November: 'November', Desember: 'December',
  },
  'zh-CN': {
    Januari: '一月', Februari: '二月', Maret: '三月', April: '四月',
    Mei: '五月', Juni: '六月', Juli: '七月', Agustus: '八月',
    September: '九月', Oktober: '十月', November: '十一月', Desember: '十二月',
  },
};

const dynamicPatterns: Array<{
  pattern: RegExp;
  en: (...groups: string[]) => string;
  zh: (...groups: string[]) => string;
}> = [
  {
    pattern: /^(\d+) berhasil, (\d+) gagal, (\d+) dilewati$/,
    en: (success, failed, skipped) => `${success} successful, ${failed} failed, ${skipped} skipped`,
    zh: (success, failed, skipped) => `成功 ${success}，失败 ${failed}，跳过 ${skipped}`,
  },
  {
    pattern: /^Import selesai: (\d+) berhasil, (\d+) gagal\.$/,
    en: (success, failed) => `Import completed: ${success} successful, ${failed} failed.`,
    zh: (success, failed) => `导入完成：成功 ${success}，失败 ${failed}。`,
  },
  {
    pattern: /^(\d+) payroll dibuat, (\d+) dilewati karena sudah tersedia\.$/,
    en: (inserted, skipped) => `${inserted} payroll records created; ${skipped} skipped because they already exist.`,
    zh: (inserted, skipped) => `已创建 ${inserted} 条薪资记录；${skipped} 条因已存在而跳过。`,
  },
  {
    pattern: /^Halaman (\d+) dari (\d+)$/,
    en: (page, total) => `Page ${page} of ${total}`,
    zh: (page, total) => `第 ${page} 页，共 ${total} 页`,
  },
];

export function translatePhrase(value: string, locale: Locale): string {
  if (locale === 'id' || !value) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.trim();
  if (!core) return value;

  const direct = dictionaries[locale][core];
  if (direct) return `${leading}${direct}${trailing}`;

  for (const item of dynamicPatterns) {
    const match = core.match(item.pattern);
    if (match) {
      const result = locale === 'en' ? item.en(...match.slice(1)) : item.zh(...match.slice(1));
      return `${leading}${result}${trailing}`;
    }
  }

  let result = core;
  for (const [source, target] of Object.entries(monthMaps[locale])) {
    result = result.replace(new RegExp(`\\b${source}\\b`, 'g'), target);
  }
  return `${leading}${result}${trailing}`;
}
